#!/usr/bin/env python3
"""Generate PBCC planning scenarios from explicit JSON inputs; standard library only."""

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def nonnegative(value, label):
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or value < 0:
        raise ValueError(f"{label} must be a finite nonnegative number")
    return value


def positive_integer(value, label):
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise ValueError(f"{label} must be a positive integer")
    return value


def calculate(a):
    members = a["member_counts"]
    dues_options = a["monthly_dues_options"]
    fleet = a["fleet_purchase_allocations"]
    if not members or not dues_options or not fleet:
        raise ValueError("Provide at least one member count, dues option, and car")
    for count in members:
        positive_integer(count, "member count")
    for dues in dues_options:
        nonnegative(dues, "monthly dues")
    for key in ("capital_per_member", "acquisition_tax_rate", "annual_entity_tax",
                "monthly_repair_reserve_contribution", "initial_repair_reserve",
                "operating_buffer_months", "annual_miles_per_car"):
        nonnegative(a[key], key)
    for group in ("monthly_costs", "one_time_costs"):
        for key, value in a[group].items():
            nonnegative(value, key)
    purchase = sum(nonnegative(car["ceiling"], "purchase allocation") for car in fleet)
    car_count = len(fleet)
    monthly = a["monthly_costs"]
    cash_expense = sum(value * car_count if key.endswith("_per_car") else value
                       for key, value in monthly.items()) + a["annual_entity_tax"] / 12
    reserve_saving = a["monthly_repair_reserve_contribution"]
    funding_need = cash_expense + reserve_saving
    tax = purchase * a["acquisition_tax_rate"]
    upfront = purchase + tax + sum(a["one_time_costs"].values())
    initial_floor = a["initial_repair_reserve"] + a["operating_buffer_months"] * cash_expense
    cases = []
    for count in members:
        capital = count * a["capital_per_member"]
        cash = capital - upfront
        for dues in dues_options:
            revenue = count * dues
            bank_draw = cash_expense - revenue
            funding_gap = funding_need - revenue
            margin = cash - initial_floor
            # Reserve contributions raise the earmarked floor rather than leaving the bank.
            breach = 0 if margin <= 0 else margin / funding_gap if funding_gap > 0 else None
            cases.append({
                "members": count, "dues": dues, "capital": capital, "cash_after_setup": cash,
                "cash_above_initial_floor": margin, "annual_dues": revenue * 12,
                "annual_funding_gap": funding_gap * 12,
                "break_even_dues": funding_need / count,
                "months_to_reserve_floor": breach,
                "bank_cash_after_year": cash - bank_draw * 12,
                "earmarked_floor_after_year": initial_floor + reserve_saving * 12,
            })
    return {"car_count": car_count, "purchase": purchase, "acquisition_tax": tax,
            "upfront": upfront, "monthly_cash_expense": cash_expense,
            "monthly_funding_need": funding_need, "initial_floor": initial_floor,
            "cases": cases}


def money(value):
    return f"-${abs(value):,.0f}" if value < 0 else f"${value:,.0f}"


def report(a, r):
    rows = [
        "# PBCC financial scenarios", "",
        f"Inputs dated {a['as_of']}. Generated by `python3 scripts/model.py --output finance/scenarios.md`.",
        "", a["status"], "",
        "## Uses of initial capital", "",
        "| Item | Amount |", "| --- | ---: |",
        f"| {r['car_count']} vehicle purchase allocations | {money(r['purchase'])} |",
        f"| Acquisition tax at assumed {a['acquisition_tax_rate']:.1%} | {money(r['acquisition_tax'])} |",
    ]
    for key, value in a["one_time_costs"].items():
        rows.append(f"| {key.replace('_', ' ').capitalize()} | {money(value)} |")
    rows += [f"| Total initial cash spent | {money(r['upfront'])} |", "",
             "Initial reserves stay in cash; they are not another setup expense.", "",
             "## Recurring annual funding", "", "| Item | Annual amount |", "| --- | ---: |"]
    for key, value in a["monthly_costs"].items():
        annual = value * 12 * (r["car_count"] if key.endswith("_per_car") else 1)
        rows.append(f"| {key.replace('_', ' ').capitalize()} | {money(annual)} |")
    rows += [
        f"| Entity tax placeholder | {money(a['annual_entity_tax'])} |",
        f"| Total external cash expense | {money(r['monthly_cash_expense'] * 12)} |",
        f"| Additional repair-reserve earmarking | {money(a['monthly_repair_reserve_contribution'] * 12)} |",
        f"| Total annual funding need | {money(r['monthly_funding_need'] * 12)} |", "",
        f"Initial cash floor: {money(r['initial_floor'])}, comprising {a['operating_buffer_months']:g} months of external operating costs plus {money(a['initial_repair_reserve'])} repair cash.",
        "Monthly reserve saving raises the earmarked floor; it is not treated as money leaving the bank.", "",
        "## Member and dues sensitivity", "",
        "| Members | Monthly dues/member | Gross capital | Cash after setup | Cash above initial floor | Annual dues | Annual funding gap | Break-even monthly dues/member | Months until reserve floor |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for c in r["cases"]:
        breach = "No projected breach" if c["months_to_reserve_floor"] is None else f"{c['months_to_reserve_floor']:.1f}"
        rows.append(f"| {c['members']} | {money(c['dues'])} | {money(c['capital'])} | {money(c['cash_after_setup'])} | {money(c['cash_above_initial_floor'])} | {money(c['annual_dues'])} | {money(c['annual_funding_gap'])} | {money(c['break_even_dues'])} | {breach} |")
    rows += ["", "Positive funding gap means additional funding is needed; negative means surplus. Break-even dues include reserve saving but not excluded economic costs.",
             "Months to floor assumes no usage revenue, unchanged costs, no major repair/claim, and monthly earmarking. A floor breach calls for a funding decision; it is not the same as bank insolvency.", "",
             "## Twelve-month bank cash versus earmarked floor", "",
             "| Members | Monthly dues/member | Bank cash after year | Earmarked floor after year |",
             "| ---: | ---: | ---: | ---: |"]
    for c in r["cases"]:
        rows.append(f"| {c['members']} | {money(c['dues'])} | {money(c['bank_cash_after_year'])} | {money(c['earmarked_floor_after_year'])} |")
    rows += ["", f"Mileage planning input: {a['annual_miles_per_car']:,.0f} miles/car/year. Costs do not automatically scale with mileage; change cost inputs when testing higher use.", "",
             "## Sources and limits", ""]
    rows.extend(f"- **{key.replace('_', ' ').capitalize()}:** {value}" for key, value in a["sources_and_limits"].items())
    rows += ["", "A reduction in quoted costs changes the result. Increasing membership improves dues coverage but also changes access. Usage fees close the gap only after incremental costs and applicable taxes. Capital left in the bank is not a guaranteed member redemption value.", ""]
    return "\n".join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assumptions", type=Path, default=ROOT / "finance/assumptions.json")
    parser.add_argument("--output", type=Path, help="Write report here; otherwise print to stdout")
    args = parser.parse_args()
    try:
        assumptions = json.loads(args.assumptions.read_text())
        output = report(assumptions, calculate(assumptions))
    except (OSError, ValueError, KeyError, TypeError) as exc:
        parser.error(str(exc))
    if args.output:
        args.output.write_text(output)
    else:
        print(output, end="")


if __name__ == "__main__":
    main()
