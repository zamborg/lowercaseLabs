#!/usr/bin/env python3
"""Generate isolated Controllr Voice audit shortcuts for testing in Apple Shortcuts."""
import argparse
from pathlib import Path
import plistlib

from gen import Workflow, make_router

OUTPUT_DIR = Path(__file__).resolve().parents[1] / "build" / "shortcut-audit"


def timer_probe(team_id):
    workflow = Workflow(team_id)
    workflow.comment("Choose one binding and check the actual duration in Clock → Timers.")
    workflow.comment("Shortcuts generated by Shortcuts Playground. Probe the Clock timer binding.")
    menu = workflow.identifier()
    choices = ("Control: 2 minutes", "Control: 83 seconds", "Direct variable", "Seconds magnitude")
    workflow.comment("- Choose one duration binding.\n- Check the live timer in Clock.")
    workflow.system("choosefrommenu", GroupingIdentifier=menu, WFControlFlowMode=0,
                    WFMenuPrompt="Which Clock duration binding should run?", WFMenuItems=list(choices))
    for choice in choices:
        workflow.system("choosefrommenu", GroupingIdentifier=menu, WFControlFlowMode=1, WFMenuItemTitle=choice)
        if choice.startswith("Control"):
            unit, magnitude = ("min", 2) if choice == choices[0] else ("sec", 83)
        else:
            seconds = workflow.output("is.workflow.actions.ask", "Test Seconds", WFInputType="Number",
                                      WFAskActionPrompt="Duration in seconds", WFAskActionDefaultAnswerNumber=83,
                                      WFAskActionAllowsDecimalNumbers=False, WFAskActionAllowsNegativeNumbers=False)
            unit, magnitude = "sec", seconds.attachment
        duration = {"Value": {"Unit": unit, "Magnitude": magnitude}, "WFSerializationType": "WFQuantityFieldValue"}
        workflow.system("timer.start", WFDuration=seconds.attachment if choice == "Direct variable" else duration)
    workflow.system("choosefrommenu", GroupingIdentifier=menu, WFControlFlowMode=2)
    return workflow.actions


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("target", choices=("timer", "router"))
    parser.add_argument("--team-id", required=True)
    opts = parser.parse_args()
    document = make_router(opts.team_id)
    if opts.target == "timer":
        document["WFWorkflowName"] = "Controllr Timer Audit"
        document["WFWorkflowActions"] = timer_probe(opts.team_id)
        document["WFWorkflowInputContentItemClasses"] = []
    else:
        document["WFWorkflowName"] = "Controllr Router Audit"
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUTPUT_DIR / (document["WFWorkflowName"] + ".xml")
    path.write_bytes(plistlib.dumps(document))
    print(f"{len(document['WFWorkflowActions'])} actions in {path}")
