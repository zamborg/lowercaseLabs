def _ensure_csrf(request: Request) -> tuple[str, bool]:
    existing = request.cookies.get(CSRF_COOKIE, "").strip()
    if existing:
        return existing, False
    return secrets.token_urlsafe(24), True


def _attach_csrf_cookie(response: Response, token: str, *, prefix: str, is_new: bool) -> Response:
    if is_new:
        response.set_cookie(
            key=CSRF_COOKIE,
            value=token,
            path=prefix or "/",
            httponly=True,
            samesite="strict",
        )
    return response


def _group_open_tasks(tasks: list[dict[str, Any]], today: date) -> list[tuple[str, list[dict[str, Any]]]]:
    overdue: list[dict[str, Any]] = []
    due_today: list[dict[str, Any]] = []
    upcoming: list[dict[str, Any]] = []
    no_date: list[dict[str, Any]] = []

    for task in tasks:
        raw_due = task.get("due")
        if not raw_due:
            no_date.append(task)
            continue
        try:
            d = date.fromisoformat(str(raw_due))
        except ValueError:
            no_date.append(task)
            continue
        if d < today:
            overdue.append(task)
        elif d == today:
            due_today.append(task)
        else:
            upcoming.append(task)

    return [
        ("Overdue", overdue),
        ("Today", due_today),
        ("Upcoming", upcoming),
        ("No date", no_date),
    ]


def _render_task_row(
    task: dict[str, Any],
    *,
    prefix: str,
    csrf_token: str,
    today: date,
    active_tag: str,
) -> str:
    tid = int(task["id"])
    is_open = task["status"] == "open"
    tags = task.get("tags") or []
    tags_str = ", ".join(tags)
    tag_qs = f"?tag={quote(active_tag, safe='')}" if active_tag else ""

    due_html = ""
    if task.get("due"):
        due_label, due_kind = _fmt_due(task["due"], today)
        due_html = f'<span class="badge badge-{due_kind}">{_e(due_label)}</span>'

    status_html = ""
    if task["status"] == "cancelled":
        status_html = '<span class="badge badge-muted">cancelled</span>'

    tag_chips = "".join(
        f'<a class="chip" href="{_e(prefix)}/?tag={quote(str(t), safe="")}">#{_e(t)}</a>' for t in tags
    )
    added_by = f'<span class="faint">added by {_e(task["created_by"])}</span>'
    done_when = (
        f'<span class="faint">done {_fmt_time(task["completed_at"])}</span>'
        if not is_open and task.get("completed_at")
        else ""
    )

    notes_html = f'<div class="task-notes">{_e(task["notes"])}</div>' if task.get("notes") else ""

    if is_open:
        left_btn = (
            f'<form class="task-check" method="post" action="{_e(prefix)}/complete{tag_qs}">'
            f'<input type="hidden" name="csrf_token" value="{_e(csrf_token)}">'
            f'<input type="hidden" name="id" value="{tid}">'
            '<button type="submit" class="secondary" title="Mark done" aria-label="Mark done">✓</button>'
            "</form>"
        )
    else:
        left_btn = (
            f'<form class="task-check" method="post" action="{_e(prefix)}/reopen{tag_qs}">'
            f'<input type="hidden" name="csrf_token" value="{_e(csrf_token)}">'
            f'<input type="hidden" name="id" value="{tid}">'
            '<button type="submit" class="ghost" title="Reopen" aria-label="Reopen">↺</button>'
            "</form>"
        )

    status_opts = "".join(
        f'<option value="{st}"{" selected" if task["status"] == st else ""}>{st}</option>'
        for st in ("open", "done", "cancelled")
    )
    edit_drawer = (
        '<details class="disclose">'
        '<summary class="btn ghost sm">Edit</summary>'
        '<div class="disclose-body">'
        f'<form class="edit-form" method="post" action="{_e(prefix)}/update{tag_qs}">'
        f'<input type="hidden" name="csrf_token" value="{_e(csrf_token)}">'
        f'<input type="hidden" name="id" value="{tid}">'
        f'<label class="field">Title<input type="text" name="title" value="{_e(task["title"])}" required></label>'
        f'<label class="field">Due date<input type="date" name="due" value="{_e(task.get("due") or "")}"></label>'
        f'<label class="field">Tags<input type="text" name="tags" value="{_e(tags_str)}" placeholder="errands, health"></label>'
        f'<label class="field">Status<select name="status">{status_opts}</select></label>'
        f'<label class="field">Notes<textarea name="notes">{_e(task.get("notes") or "")}</textarea></label>'
        '<div class="row"><button type="submit" class="sm">Save</button></div>'
        "</form>"
        "</div></details>"
    )
    delete_drawer = (
        '<details class="disclose">'
        '<summary class="btn ghost sm">Delete</summary>'
        '<div class="disclose-body">'
        f'<form class="inline" method="post" action="{_e(prefix)}/delete{tag_qs}">'
        f'<input type="hidden" name="csrf_token" value="{_e(csrf_token)}">'
        f'<input type="hidden" name="id" value="{tid}">'
        '<button type="submit" class="danger solid sm">Delete task</button>'
        "</form>"
        "</div></details>"
    )

    row_cls = "task-row" if is_open else "task-row task-done"
    return (
        f'<div class="{row_cls}">'
        f"{left_btn}"
        '<div class="task-body">'
        f'<div class="task-title">{_e(task["title"])}</div>'
        f"{notes_html}"
        f'<div class="task-meta">{due_html}{status_html}{tag_chips}{added_by}{done_when}</div>'
        "</div>"
        f'<div class="task-actions">{edit_drawer}{delete_drawer}</div>'
        "</div>"
    )


def create_ui_app(store: TasksStore, *, module_secret: str) -> Starlette:
    """Create the mobile-first server-rendered owner Tasks UI."""

    def _verify_owner(request: Request) -> str | None:
        try:
            caller = verify_http_caller(dict(request.headers), secret=module_secret)
        except CallerVerificationError:
            return None
        return caller.client_name

    def _verify_csrf(request: Request, form: Any) -> bool:
        cookie_csrf = request.cookies.get(CSRF_COOKIE, "").strip()
        form_csrf = str(form.get("csrf_token", "")).strip()
        return bool(cookie_csrf and form_csrf and hmac.compare_digest(cookie_csrf, form_csrf))

    def _back_url(prefix: str, active_tag: str, *, notice: str | None = None, error: str | None = None) -> str:
        params: list[str] = []
        if active_tag:
            params.append(f"tag={quote(active_tag, safe='')}")
        if notice:
            params.append(f"notice={quote(notice)}")
        if error:
            params.append(f"error={quote(error)}")
        qs = f"?{'&'.join(params)}" if params else ""
        return f"{prefix}/{qs}"

    async def healthz(request: Request) -> JSONResponse:
        return JSONResponse({"ok": True, "module": "tasks", "service": "ui"})

    async def index_view(request: Request) -> Response:
        if _verify_owner(request) is None:
            return HTMLResponse("<h1>Forbidden</h1>", status_code=403)
        pref = _prefix(request)
        csrf_token, is_new = _ensure_csrf(request)

        active_tag = request.query_params.get("tag", "").strip().lower()
        notice = request.query_params.get("notice", "").strip()
        error = request.query_params.get("error", "").strip()
        today = datetime.now(UTC).date()

        data = await store.list_for_ui(tag=active_tag or None, done_limit=50)
        open_tasks: list[dict[str, Any]] = data["open"]
        done_tasks: list[dict[str, Any]] = data["done"]
        all_tags: list[str] = data["tags"]

        banners = ""
        if error:
            banners += f'<div class="notice notice-err" role="alert"><div>{_e(error)}</div></div>'
        if notice:
            banners += f'<div class="notice notice-ok" role="status"><div>{_e(notice)}</div></div>'

        tag_qs = f"?tag={quote(active_tag, safe='')}" if active_tag else ""
        add_panel = f"""
        <div class="panel" style="margin-bottom:24px"><div class="panel-body">
          <form class="add-form" method="post" action="{_e(pref)}/add{tag_qs}">
            <input type="hidden" name="csrf_token" value="{_e(csrf_token)}">
            <div class="add-row">
              <label class="field grow">New task
                <input type="text" name="title" placeholder="What needs to get done?" required>
              </label>
              <label class="field">Due
                <input type="date" name="due">
              </label>
              <button type="submit">Add</button>
            </div>
            <details class="add-more">
              <summary>Notes &amp; tags</summary>
              <div class="add-form">
                <label class="field">Tags <span class="hint">· comma-separated</span>
                  <input type="text" name="tags" value="{_e(active_tag)}" placeholder="errands, home, finance">
                </label>
                <label class="field">Notes
                  <textarea name="notes" placeholder="Optional details..."></textarea>
                </label>
              </div>
            </details>
          </form>
        </div></div>
        """

        tag_bar = ""
        if all_tags:
            chips = [
                f'<a class="chip{" active" if not active_tag else ""}" href="{_e(pref)}/">All</a>'
            ]
            for t in all_tags:
                cls = "chip active" if active_tag == t else "chip"
                chips.append(f'<a class="{cls}" href="{_e(pref)}/?tag={quote(t, safe="")}">#{_e(t)}</a>')
            tag_bar = f'<div class="chips" style="margin-bottom:18px">{"".join(chips)}</div>'

        groups_html = ""
        if not open_tasks:
            empty_msg = f"No open tasks tagged #{_e(active_tag)}." if active_tag else "Nothing on your list."
            groups_html = f'<div class="panel"><p class="empty">{empty_msg}</p></div>'
        else:
            for group_name, group_items in _group_open_tasks(open_tasks, today):
                if not group_items:
                    continue
                rows_html = "".join(
                    _render_task_row(
                        t, prefix=pref, csrf_token=csrf_token, today=today, active_tag=active_tag
                    )
                    for t in group_items
                )
                groups_html += (
                    '<section class="section" style="margin-top:20px">'
                    f'<div class="section-head"><h2>{_e(group_name)}</h2><span class="meta">{len(group_items)}</span></div>'
                    f'<div class="panel">{rows_html}</div>'
                    "</section>"
                )

        done_html = ""
        if done_tasks:
            done_rows = "".join(
                _render_task_row(
                    t, prefix=pref, csrf_token=csrf_token, today=today, active_tag=active_tag
                )
                for t in done_tasks
            )
            done_html = (
                '<section class="section">'
                f'<div class="section-head"><h2>Done</h2><span class="meta">{len(done_tasks)}</span></div>'
                f'<div class="panel">{done_rows}</div>'
                "</section>"
            )

        body = (
            '<header class="page-head"><div><h1>Tasks</h1>'
            '<p class="lede">Personal todo list for the human owner.</p></div></header>'
            + banners
            + add_panel
            + tag_bar
            + groups_html
            + done_html
        )
        resp = HTMLResponse(_page(title="Tasks", prefix=pref, body=body, open_count=len(open_tasks)))
        return _attach_csrf_cookie(resp, csrf_token, prefix=pref, is_new=is_new)

    async def add_action(request: Request) -> Response:
        if _verify_owner(request) is None:
            return HTMLResponse("<h1>Forbidden</h1>", status_code=403)
        pref = _prefix(request)
        active_tag = request.query_params.get("tag", "").strip().lower()
        form = await request.form()
        if not _verify_csrf(request, form):
            return HTMLResponse("<h1>Invalid CSRF token</h1>", status_code=403)

        title = str(form.get("title", "")).strip()
        notes = str(form.get("notes", ""))
        due = str(form.get("due", "")).strip() or None
        tags = str(form.get("tags", ""))
        try:
            await store.add_task(title=title, created_by="owner", notes=notes, due=due, tags=tags)
        except Exception as exc:
            return RedirectResponse(_back_url(pref, active_tag, error=str(exc)), status_code=303)
        return RedirectResponse(_back_url(pref, active_tag, notice="Task added."), status_code=303)

    async def complete_action(request: Request) -> Response:
        if _verify_owner(request) is None:
            return HTMLResponse("<h1>Forbidden</h1>", status_code=403)
        pref = _prefix(request)
        active_tag = request.query_params.get("tag", "").strip().lower()
        form = await request.form()
        if not _verify_csrf(request, form):
            return HTMLResponse("<h1>Invalid CSRF token</h1>", status_code=403)
        with contextlib.suppress(Exception):
            await store.complete_task(int(str(form.get("id", ""))))
        return RedirectResponse(_back_url(pref, active_tag, notice="Task completed."), status_code=303)

    async def reopen_action(request: Request) -> Response:
        if _verify_owner(request) is None:
            return HTMLResponse("<h1>Forbidden</h1>", status_code=403)
        pref = _prefix(request)
        active_tag = request.query_params.get("tag", "").strip().lower()
        form = await request.form()
        if not _verify_csrf(request, form):
            return HTMLResponse("<h1>Invalid CSRF token</h1>", status_code=403)
        with contextlib.suppress(Exception):
            await store.reopen_task(int(str(form.get("id", ""))))
        return RedirectResponse(_back_url(pref, active_tag, notice="Task reopened."), status_code=303)

    async def update_action(request: Request) -> Response:
        if _verify_owner(request) is None:
            return HTMLResponse("<h1>Forbidden</h1>", status_code=403)
        pref = _prefix(request)
        active_tag = request.query_params.get("tag", "").strip().lower()
        form = await request.form()
        if not _verify_csrf(request, form):
            return HTMLResponse("<h1>Invalid CSRF token</h1>", status_code=403)
        try:
            task_id = int(str(form.get("id", "")))
            await store.update_task(
                task_id,
                title=str(form.get("title", "")),
                notes=str(form.get("notes", "")),
                due=str(form.get("due", "")).strip() or None,
                tags=str(form.get("tags", "")),
                status=str(form.get("status", "open")),
            )
        except Exception as exc:
            return RedirectResponse(_back_url(pref, active_tag, error=str(exc)), status_code=303)
        return RedirectResponse(_back_url(pref, active_tag, notice="Task updated."), status_code=303)

    async def delete_action(request: Request) -> Response:
        if _verify_owner(request) is None:
            return HTMLResponse("<h1>Forbidden</h1>", status_code=403)
        pref = _prefix(request)
        active_tag = request.query_params.get("tag", "").strip().lower()
        form = await request.form()
        if not _verify_csrf(request, form):
            return HTMLResponse("<h1>Invalid CSRF token</h1>", status_code=403)
        with contextlib.suppress(Exception):
            await store.delete_task(int(str(form.get("id", ""))))
        return RedirectResponse(_back_url(pref, active_tag, notice="Task deleted."), status_code=303)

    return Starlette(
        routes=[
            Route("/healthz", healthz, methods=["GET"]),
            Route("/", index_view, methods=["GET"]),
            Route("/add", add_action, methods=["POST"]),
            Route("/complete", complete_action, methods=["POST"]),
            Route("/reopen", reopen_action, methods=["POST"]),
            Route("/update", update_action, methods=["POST"]),
            Route("/delete", delete_action, methods=["POST"]),
        ]
    )
