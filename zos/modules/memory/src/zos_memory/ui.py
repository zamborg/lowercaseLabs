def _e(val: Any) -> str:
    return html.escape("" if val is None else str(val), quote=True)


def _prefix(request: Request) -> str:
    raw = request.headers.get("x-forwarded-prefix", "").strip().rstrip("/")
    return raw if raw.startswith("/") else ""


def _fmt_time(iso_str: str | None) -> str:
    """Compact timestamp ("Nov 26, 14:02"), full ISO value on hover."""
    if not iso_str:
        return ""
    try:
        dt = datetime.fromisoformat(str(iso_str).replace("Z", "+00:00"))
    except ValueError:
        return _e(iso_str)
    day = f"{dt:%b} {dt.day}" + ("" if dt.year == datetime.now(UTC).year else f", {dt.year}")
    return f'<time title="{_e(iso_str)}">{day}, {dt:%H:%M}</time>'


